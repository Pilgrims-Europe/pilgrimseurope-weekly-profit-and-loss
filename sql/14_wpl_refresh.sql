-- Materialise the weekly P&L views into tables for the app.
-- The views read 557 M GL rows and take about 20 seconds. The tables answer in under a second.
-- The task runs at 11:00 UTC each day, after the 10:15 UTC GL and goods movement loads.
CREATE OR REPLACE PROCEDURE DEV_ANALYTICS.FINANCE_PL_WEEKLY.WPL_REFRESH()
RETURNS VARCHAR
LANGUAGE SQL
COMMENT = 'Weekly P&L app: rebuild the WPL_T_* tables from the WPL_* views.'
AS
$$
BEGIN
    CREATE OR REPLACE TABLE DEV_ANALYTICS.FINANCE_PL_WEEKLY.WPL_T_WEEKLY_PL
        COMMENT = 'Weekly P&L app: copy of WPL_WEEKLY_PL, rebuilt daily by WPL_REFRESH.'
        AS SELECT *, CURRENT_TIMESTAMP() AS REFRESHED_AT FROM DEV_ANALYTICS.FINANCE_PL_WEEKLY.WPL_WEEKLY_PL;
    CREATE OR REPLACE TABLE DEV_ANALYTICS.FINANCE_PL_WEEKLY.WPL_T_GL_WEEK
        COMMENT = 'Weekly P&L app: copy of WPL_GL_WEEK (GL detail by account), rebuilt daily by WPL_REFRESH.'
        AS SELECT * FROM DEV_ANALYTICS.FINANCE_PL_WEEKLY.WPL_GL_WEEK;
    CREATE OR REPLACE TABLE DEV_ANALYTICS.FINANCE_PL_WEEKLY.WPL_T_KILL_POULTRY
        COMMENT = 'Weekly P&L app: copy of WPL_KILL_POULTRY, rebuilt daily by WPL_REFRESH.'
        AS SELECT * FROM DEV_ANALYTICS.FINANCE_PL_WEEKLY.WPL_KILL_POULTRY;
    CREATE OR REPLACE TABLE DEV_ANALYTICS.FINANCE_PL_WEEKLY.WPL_T_KILL_POULTRY_CODE
        COMMENT = 'Weekly P&L app: copy of WPL_KILL_POULTRY_CODE, rebuilt daily by WPL_REFRESH.'
        AS SELECT * FROM DEV_ANALYTICS.FINANCE_PL_WEEKLY.WPL_KILL_POULTRY_CODE;
    CREATE OR REPLACE TABLE DEV_ANALYTICS.FINANCE_PL_WEEKLY.WPL_T_KILL_PORK
        COMMENT = 'Weekly P&L app: copy of WPL_KILL_PORK, rebuilt daily by WPL_REFRESH.'
        AS SELECT * FROM DEV_ANALYTICS.FINANCE_PL_WEEKLY.WPL_KILL_PORK;
    CREATE OR REPLACE TABLE DEV_ANALYTICS.FINANCE_PL_WEEKLY.WPL_T_KILL_PORK_TYPE
        COMMENT = 'Weekly P&L app: copy of WPL_KILL_PORK_TYPE (pork kill by provenance), rebuilt daily by WPL_REFRESH.'
        AS SELECT * FROM DEV_ANALYTICS.FINANCE_PL_WEEKLY.WPL_KILL_PORK_TYPE;
    CREATE OR REPLACE TABLE DEV_ANALYTICS.FINANCE_PL_WEEKLY.WPL_T_DQ_FRESHNESS
        COMMENT = 'Weekly P&L app: copy of WPL_DQ_FRESHNESS, rebuilt daily by WPL_REFRESH.'
        AS SELECT *, CURRENT_TIMESTAMP() AS REFRESHED_AT FROM DEV_ANALYTICS.FINANCE_PL_WEEKLY.WPL_DQ_FRESHNESS;
    CREATE OR REPLACE TABLE DEV_ANALYTICS.FINANCE_PL_WEEKLY.WPL_T_DQ_UNMAPPED
        COMMENT = 'Weekly P&L app: copy of WPL_DQ_UNMAPPED, rebuilt daily by WPL_REFRESH.'
        AS SELECT * FROM DEV_ANALYTICS.FINANCE_PL_WEEKLY.WPL_DQ_UNMAPPED;
    RETURN 'WPL_T_* tables rebuilt at ' || CURRENT_TIMESTAMP()::VARCHAR;
END;
$$;

CREATE OR REPLACE TASK DEV_ANALYTICS.FINANCE_PL_WEEKLY.WPL_REFRESH_TASK
    WAREHOUSE = STAGING_WH
    SCHEDULE = 'USING CRON 0 11 * * * UTC'
    COMMENT = 'Weekly P&L app: rebuild the WPL_T_* tables daily at 11:00 UTC, after the 10:15 UTC GL load.'
AS
    CALL DEV_ANALYTICS.FINANCE_PL_WEEKLY.WPL_REFRESH();

ALTER TASK DEV_ANALYTICS.FINANCE_PL_WEEKLY.WPL_REFRESH_TASK RESUME;
