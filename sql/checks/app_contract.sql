-- App contract check: the tables and views that app/lib/wpl.ts reads have the columns it reads.
-- Each block selects those columns with WHERE FALSE, so the check passes when it returns no rows.
-- A missing or renamed column fails the query with "invalid identifier" and names the column.
-- Run: scripts/check-tie-out.ps1 -Check app_contract [-Schema FINANCE_PL_WEEKLY_WBW]. The script swaps the schema name.
-- When wpl.ts reads a new column, add it here. app/__tests__/lib/wpl-contract.test.ts checks that each object it reads has a block.
SELECT 'WPL_SITE' AS CHECK_NAME FROM (
    SELECT SITE, SITE_KIND, SITE_ORDER
    FROM DEV_ANALYTICS.FINANCE_PL_WEEKLY.WPL_SITE WHERE FALSE)
UNION ALL SELECT 'WPL_WEEK' FROM (
    SELECT WEEK_START, FISCAL_WEEK, FISCAL_YEAR, FISCAL_YEAR_PERIOD, FISCAL_MONTH_NAME, FISCAL_QUARTER
    FROM DEV_ANALYTICS.FINANCE_PL_WEEKLY.WPL_WEEK WHERE FALSE)
UNION ALL SELECT 'WPL_LINE' FROM (
    SELECT LINE_ID, LINE_GROUP, LINE_NAME, SOURCE_TYPE, SOURCE_SYSTEM, RAG, REASON, RULE, UNIT, TICKET, COMPONENTS, LAYOUT,
           RATIO_NUM, RATIO_DEN, RATIO_SCALE
    FROM DEV_ANALYTICS.FINANCE_PL_WEEKLY.WPL_LINE WHERE FALSE)
UNION ALL SELECT 'WPL_T_WEEKLY_PL' FROM (
    SELECT WEEK_START, FISCAL_WEEK, SITE, SITE_KIND, SITE_ORDER, LINE_ID, LINE_GROUP, LINE_NAME, LAYOUT, SOURCE_TYPE,
           SOURCE_SYSTEM, RAG, REASON, RULE, UNIT, TICKET, STATUS, VALUE, ACTUAL_VALUE, MISSING_COMPONENTS, COMPONENTS
    FROM DEV_ANALYTICS.FINANCE_PL_WEEKLY.WPL_T_WEEKLY_PL WHERE FALSE)
UNION ALL SELECT 'WPL_T_GL_WEEK' FROM (
    SELECT SITE, WEEK_START, LINE_ID, GLACCOUNT, ACCOUNTNAME, LINE_ITEMS, VALUE
    FROM DEV_ANALYTICS.FINANCE_PL_WEEKLY.WPL_T_GL_WEEK WHERE FALSE)
UNION ALL SELECT 'WPL_T_SALES_DETAIL' FROM (
    SELECT SITE, WEEK_START, IS_INTERCO, EDIBLE_KG, GSV, OSC, NSV, STD_COS, STD_MEAT, STD_LABOUR, STD_INGREDIENTS,
           STD_PACKAGING, STD_FREIGHT, SOLD_TO, CUSTOMER_NAME, CATEGORY, BUSINESS_UNIT, MATERIAL_CODE, MATERIAL_DESC
    FROM DEV_ANALYTICS.FINANCE_PL_WEEKLY.WPL_T_SALES_DETAIL WHERE FALSE)
UNION ALL SELECT 'WPL_T_KILL_POULTRY' FROM (
    SELECT SITE, WEEK_START, KILL_DATE, LOADS, BIRDS_DELIVERED, DOA, CONDEMNED, BIRDS_KILLED
    FROM DEV_ANALYTICS.FINANCE_PL_WEEKLY.WPL_T_KILL_POULTRY WHERE FALSE)
UNION ALL SELECT 'WPL_T_KILL_POULTRY_CODE' FROM (
    SELECT SITE, WEEK_START, CODE, CODE_NAME, CALCULATIONCATEGORY, HEAD
    FROM DEV_ANALYTICS.FINANCE_PL_WEEKLY.WPL_T_KILL_POULTRY_CODE WHERE FALSE)
UNION ALL SELECT 'WPL_T_KILL_PORK' FROM (
    SELECT SITE, WEEK_START, KILL_DATE, BOOKINGS, PIGS_DELIVERED, DOA, DIP, CASUALTY, TC_PRODUCER_RESP, TC_FACTORY_RESP,
           KILLED_QTY, PIGS_KILLED
    FROM DEV_ANALYTICS.FINANCE_PL_WEEKLY.WPL_T_KILL_PORK WHERE FALSE)
UNION ALL SELECT 'WPL_T_DQ_FRESHNESS' FROM (
    SELECT SOURCE, OBJECT_NAME, LAST_LOADED, DATA_TO, REFRESHED_AT
    FROM DEV_ANALYTICS.FINANCE_PL_WEEKLY.WPL_T_DQ_FRESHNESS WHERE FALSE)
UNION ALL SELECT 'WPL_T_DQ_PRODUCTION_TONNAGE' FROM (
    SELECT SITE, WEEK_START, FISCAL_WEEK, PRODUCTION_T, SALES_T, SALES_INEDIBLE_T, INTERNAL_SALES_T, FG_STOCK_T,
           DIFFERENCE_T, DIFFERENCE_PCT
    FROM DEV_ANALYTICS.FINANCE_PL_WEEKLY.WPL_T_DQ_PRODUCTION_TONNAGE WHERE FALSE)
UNION ALL SELECT 'WPL_T_DQ_UNMAPPED' FROM (
    SELECT SITE, GLACCOUNT, ACCOUNTNAME, GROUP_NAME, LINE_ITEMS, VALUE
    FROM DEV_ANALYTICS.FINANCE_PL_WEEKLY.WPL_T_DQ_UNMAPPED WHERE FALSE);
