-- Data and quality for the weekly P&L app.

-- Freshness: last data date and last load time for each source.
-- Two steps. WPL_REFRESH first copies WPL_DQ_DATA_TO to the table WPL_T_DQ_DATA_TO. WPL_DQ_FRESHNESS then joins that table
-- to INFORMATION_SCHEMA. With the data views in the same query as INFORMATION_SCHEMA, Snowflake failed with
-- "Error parsing JSON: invalid UTF-8 sequence" (2026-11-18, history from 2024-12-30).
CREATE OR REPLACE VIEW DEV_ANALYTICS.FINANCE_PL_WEEKLY.WPL_DQ_DATA_TO
COMMENT = 'Weekly P&L app: last data date for each source (pilot or kill sites).'
AS
SELECT 'GL line items' AS SOURCE, MAX(WEEK_START) + 6 AS DATA_TO FROM DEV_ANALYTICS.FINANCE_PL_WEEKLY.WPL_GL_WEEK
UNION ALL SELECT 'Goods movements', MAX(WEEK_START) + 6 FROM DEV_ANALYTICS.FINANCE_PL_WEEKLY.WPL_MOVEMENT_WEEK
UNION ALL SELECT 'COPA (gold)', MAX(POSTING_DATE) FROM PROD_ANALYTICS.FINANCE_MT.FACT_COPAPEUS4 WHERE RECORD_SOURCE = 'Actual' AND PLANT IN ('2504', '2506')
UNION ALL SELECT 'COPA (silver)', MAX(POSTING_DATE) FROM PROD_STAGING.FINANCE.C_PROFITABILITYANAL_COSTING_PEU_SAP_STG WHERE PLANT IN ('2504', '2506')
UNION ALL SELECT 'Mtech loads', MAX(KILL_DATE) FROM DEV_ANALYTICS.FINANCE_PL_WEEKLY.WPL_KILL_POULTRY
UNION ALL SELECT 'Hellenic bookings', MAX(KILL_DATE) FROM DEV_ANALYTICS.FINANCE_PL_WEEKLY.WPL_KILL_PORK
UNION ALL SELECT 'Arolink yield', MAX(WEEK_START) + 6 FROM DEV_ANALYTICS.FINANCE_PL_WEEKLY.WPL_YIELD_WEEK;

-- The view below needs the table. WPL_REFRESH rebuilds it each day.
CREATE TABLE IF NOT EXISTS DEV_ANALYTICS.FINANCE_PL_WEEKLY.WPL_T_DQ_DATA_TO
    COMMENT = 'Weekly P&L app: copy of WPL_DQ_DATA_TO, rebuilt daily by WPL_REFRESH.'
    AS SELECT * FROM DEV_ANALYTICS.FINANCE_PL_WEEKLY.WPL_DQ_DATA_TO;

CREATE OR REPLACE VIEW DEV_ANALYTICS.FINANCE_PL_WEEKLY.WPL_DQ_FRESHNESS
COMMENT = 'Weekly P&L app: last data date (pilot or kill sites) and last load time for each source table.'
AS
WITH t AS (
    SELECT 'GL line items' AS SOURCE, 'PROD_RAW.SAP.C_ACTUALPLANGL' AS OBJECT_NAME, LAST_ALTERED FROM PROD_RAW.INFORMATION_SCHEMA.TABLES WHERE TABLE_SCHEMA = 'SAP' AND TABLE_NAME = 'jbs_bw4_hana.edw.fmco.figl/C_ACTUALPLANGL'
    UNION ALL SELECT 'Goods movements', 'PROD_RAW.SAP.C_GOODSMOVEMENTDOCUMENTS', LAST_ALTERED FROM PROD_RAW.INFORMATION_SCHEMA.TABLES WHERE TABLE_SCHEMA = 'SAP' AND TABLE_NAME = 'jbs_bw4_hana.edw.scm.mmic/C_GOODSMOVEMENTDOCUMENTS'
    UNION ALL SELECT 'COPA (gold)', 'PROD_ANALYTICS.FINANCE_MT.FACT_COPAPEUS4', LAST_ALTERED FROM PROD_ANALYTICS.INFORMATION_SCHEMA.TABLES WHERE TABLE_SCHEMA = 'FINANCE_MT' AND TABLE_NAME = 'FACT_COPAPEUS4'
    UNION ALL SELECT 'COPA (silver)', 'PROD_STAGING.FINANCE.C_PROFITABILITYANAL_COSTING_PEU_SAP_STG', LAST_ALTERED FROM PROD_STAGING.INFORMATION_SCHEMA.TABLES WHERE TABLE_SCHEMA = 'FINANCE' AND TABLE_NAME = 'C_PROFITABILITYANAL_COSTING_PEU_SAP_STG'
    UNION ALL SELECT 'Mtech loads', 'PROD_RAW.MTECH.PMTSPROCRECVTRANS', LAST_ALTERED FROM PROD_RAW.INFORMATION_SCHEMA.TABLES WHERE TABLE_SCHEMA = 'MTECH' AND TABLE_NAME = 'PMTSPROCRECVTRANS'
    UNION ALL SELECT 'Hellenic bookings', 'PROD_RAW.HELLENIC.STG_PIG_BOOKING DETAIL__live', LAST_ALTERED FROM PROD_RAW.INFORMATION_SCHEMA.TABLES WHERE TABLE_SCHEMA = 'HELLENIC' AND TABLE_NAME = 'STG_PIG_BOOKING DETAIL__live'
    UNION ALL SELECT 'Arolink yield', 'PROD_ANALYTICS.OPERATIONS_MT.FACTS_YIELD', LAST_ALTERED FROM PROD_ANALYTICS.INFORMATION_SCHEMA.TABLES WHERE TABLE_SCHEMA = 'OPERATIONS_MT' AND TABLE_NAME = 'FACTS_YIELD'
)
SELECT t.SOURCE, t.OBJECT_NAME, t.LAST_ALTERED AS LAST_LOADED, d.DATA_TO
FROM t LEFT JOIN DEV_ANALYTICS.FINANCE_PL_WEEKLY.WPL_T_DQ_DATA_TO d ON d.SOURCE = t.SOURCE;

-- P&L accounts (4xxx to 7xxx) with postings at the pilot sites in FY2026 that no template line uses.
-- Sales, cost of sales and direct wages are expected here: COPA and the standard cost lines carry them.
CREATE OR REPLACE VIEW DEV_ANALYTICS.FINANCE_PL_WEEKLY.WPL_DQ_UNMAPPED
COMMENT = 'Weekly P&L app: P&L GL accounts with FY2026 postings at Redruth or Bromborough (ledger 1L) that no template line uses, with P&L group and value.'
AS
SELECT
    s.SITE,
    g.GLACCOUNT,
    p.ACCOUNTNAME,
    p.GROUP_NAME,
    COUNT(*)                                    AS LINE_ITEMS,
    -SUM(g.AMOUNTINCOMPANYCODECURRENCY)         AS VALUE
FROM PROD_RAW.SAP."jbs_bw4_hana.edw.fmco.figl/C_ACTUALPLANGL" g
JOIN DEV_ANALYTICS.FINANCE_PL_WEEKLY.WPL_SITE s ON s.PROFIT_CENTER = g.PROFITCENTER
LEFT JOIN (
    SELECT DISTINCT ACCOUNT, ACCOUNTNAME, GROUP_NAME
    FROM FINANCE_STORE.P_AND_L.PL_APP_FACT_BASE
    WHERE COMPANY_CODE = 'C125' AND A_B = 'ACTUAL'
) p ON p.ACCOUNT = g.GLACCOUNT
WHERE g.COMPANYCODE = '125'
  AND g.LEDGER = '1L'
  AND g.POSTINGDATE >= '20251229'
  AND g.POSTINGDATE <> '00000000'
  AND g.GLACCOUNT BETWEEN '0004000000' AND '0007999999'
  AND g.GLACCOUNT NOT IN (SELECT GLACCOUNT FROM DEV_ANALYTICS.FINANCE_PL_WEEKLY.WPL_GL_ACCOUNT_MAP)
GROUP BY ALL;
